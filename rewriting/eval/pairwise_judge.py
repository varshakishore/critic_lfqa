"""Behavioural eval, pairwise: an LLM judge picks the better of two answers.

Replaces critique counting, which failed its ceiling check (the critic gives the luna
rewrite as many critiques as the original) and is noisy (a re-critique of the same
answer flags only ~55% of the same spans). The judge prompt is the team's standard
pairwise prompt, unchanged; the judge sees the question and the two *answers*
(final_response, no trace), so it can check citation format and relevance but not
whether a snippet supports its claim.

Every comparison is judged in both orders (A/B swapped) to cancel position bias;
`--repeats` re-judges identical prompts to measure the judge's own reliability.
Answers are matched on (record_idx, sample_idx). Resumable: rows already in
eval/pairwise/<A>__vs__<B>.jsonl are skipped, failures are retried on the next run.

Score for B: per judgment B win = 1, A win = 0, Tie / Both Bad = 0.5; averaged within
a question, then bootstrapped over questions.

    python -u eval/pairwise_judge.py --pairs original:rewrite_luna --repeats 2     # validate (~$5)
    python -u eval/pairwise_judge.py --pairs base_sft:full_sft_b0.05_ep2 base_sft:local_sft_b0.05_ep1
    python eval/pairwise_judge.py --pairs original:rewrite_luna --report-only
"""
import argparse
import collections
import json
import os
import threading
from concurrent.futures import ThreadPoolExecutor, as_completed
from typing import Any, Dict, Optional

import numpy as np

from score_eval import HERE, MODEL_COSTS, read_jsonl

llm_judge_prompt = """In this task, you will be given the following:
 - question: a question written by a user
 - model responses: reports generated by two (or more) models in response to the question
You will be asked to choose which model response is better.

Factors to consider when comparing the model responses:
1. Completeness: Does the response address all aspects of the question?
2. Relevance: Are the claims in the response relevant to the question?
3. Clarity: Are all claims supported with relevant citations?
4. Citations: Are the citations relevant and properly formatted?
5. Organization: Is the response well-organized and easy to follow?

Your answer should be in the following JSON format.
{{
"reasoning": reason about which answer is better,
"rating": A/B/Both Bad/Tie
}}

Question: {}

Response A: {}

Response B: {}
"""


def extract_json_from_response(response: str) -> Optional[Dict[str, Any]]:
    json_start = response.find("{")
    json_end = response.rfind("}") + 1
    if json_start == -1 or json_end == -1:
        return None
    try:
        return json.loads(response[json_start:json_end])
    except json.JSONDecodeError:
        try:
            return json.loads(response[json_start:json_end] + "]}")
        except json.JSONDecodeError:
            pass
        return None


def parse_rating(response: str) -> Optional[str]:
    """'A' | 'B' | 'Tie' | 'Both Bad', or None. JSON first, then the same string
    fallbacks as the reference implementation, extended to Tie / Both Bad."""
    out = extract_json_from_response(response)
    if out is not None and isinstance(out.get("rating"), str):
        r = out["rating"].strip().strip('"').lower()
        return {"a": "A", "b": "B", "tie": "Tie", "both bad": "Both Bad"}.get(r)
    for label in ("A", "B", "Tie", "Both Bad"):
        if f'"rating": "{label}"' in response or f'"rating": {label}' in response:
            return label
    return None


def judge_one(client, args, job, out_path, lock, budget):
    if budget["stop"].is_set():
        return
    first, second = (job["a"], job["b"]) if job["order"] == "AB" else (job["b"], job["a"])
    prompt = llm_judge_prompt.format(job["question"], first["final_response"].strip(),
                                     second["final_response"].strip())
    resp = client.responses.create(model=args.judge, input=prompt)
    text = resp.output_text
    rating = parse_rating(text)
    if rating is None:
        print(f"  [unparsed] rec {job['record_idx']} s{job['sample_idx']} {job['order']}: {text[:200]!r}")
        return  # not written, so a re-run retries it
    # Map the positional rating back to the model that won.
    shown = {"A": first["model"], "B": second["model"]}
    winner = shown.get(rating, rating)  # model name, or 'Tie' / 'Both Bad'
    in_price, out_price = MODEL_COSTS.get(args.judge, (0.0, 0.0))
    cost = (resp.usage.input_tokens * in_price + resp.usage.output_tokens * out_price) / 1e6
    row = {"record_idx": job["record_idx"], "sample_idx": job["sample_idx"], "order": job["order"],
           "repeat": job["repeat"], "model_a": job["a"]["model"], "model_b": job["b"]["model"],
           "shown_first": first["model"], "rating": rating, "winner": winner,
           "judge": args.judge, "response": text, "cost": cost}
    with lock:
        with open(out_path, "a") as f:
            f.write(json.dumps(row) + "\n")
        budget["spent"] += cost
        if budget["spent"] >= args.cost_limit and not budget["stop"].is_set():
            budget["stop"].set()
            print(f"!! cost limit ${args.cost_limit:.2f} reached; not starting new judgments")


def run_pair(a_name, b_name, args, budget):
    from openai import OpenAI
    client = OpenAI(api_key=os.environ["OPENAI_API_KEY"])
    gens = {m: {(g["record_idx"], g["sample_idx"]): g for g in read_jsonl(os.path.join(args.gen_dir, f"{m}.jsonl"))}
            for m in (a_name, b_name)}
    keys = sorted(set(gens[a_name]) & set(gens[b_name]))
    out_path = os.path.join(args.out_dir, f"{a_name}__vs__{b_name}.jsonl")
    done = {(r["record_idx"], r["sample_idx"], r["order"], r["repeat"]) for r in read_jsonl(out_path)}
    jobs = [{"record_idx": q, "sample_idx": s, "order": o, "repeat": rep, "question": gens[a_name][(q, s)]["question"],
             "a": gens[a_name][(q, s)], "b": gens[b_name][(q, s)]}
            for (q, s) in keys for o in ("AB", "BA") for rep in range(args.repeats)
            if (q, s, o, rep) not in done]
    print(f"[{a_name} vs {b_name}] {len(keys)} matched answers x 2 orders x {args.repeats} repeats: "
          f"{len(done)} done, {len(jobs)} to go")
    lock = threading.Lock()
    with ThreadPoolExecutor(max_workers=args.workers) as ex:
        futs = {ex.submit(judge_one, client, args, j, out_path, lock, budget): j for j in jobs}
        for i, fut in enumerate(as_completed(futs), 1):
            try:
                fut.result()
            except Exception as e:
                j = futs[fut]
                print(f"  [fail] rec {j['record_idx']} s{j['sample_idx']} {j['order']}: {type(e).__name__}: {e}")
            if i % 20 == 0 or i == len(jobs):
                print(f"  {i}/{len(jobs)}  spent ${budget['spent']:.2f}", flush=True)


def report(a_name, b_name, args):
    rows = read_jsonl(os.path.join(args.out_dir, f"{a_name}__vs__{b_name}.jsonl"))
    if not rows:
        print(f"[{a_name} vs {b_name}] no judgments yet")
        return
    score = {b_name: 1.0, a_name: 0.0, "Tie": 0.5, "Both Bad": 0.5}
    outcome = collections.Counter(r["winner"] for r in rows)
    print(f"\n=== {a_name} (A) vs {b_name} (B): {len(rows)} judgments, "
          f"{len({r['record_idx'] for r in rows})} questions, spend ${sum(r['cost'] for r in rows):.2f}")
    print("  outcomes: " + ", ".join(f"{k} {v} ({100 * v / len(rows):.0f}%)"
                                     for k, v in [(b_name, outcome[b_name]), (a_name, outcome[a_name]),
                                                  ("Tie", outcome["Tie"]), ("Both Bad", outcome["Both Bad"])]))

    by_q = collections.defaultdict(list)
    for r in rows:
        by_q[r["record_idx"]].append(score[r["winner"]])
    q = np.array([np.mean(v) for v in by_q.values()])
    rng = np.random.default_rng(0)
    boots = q[rng.integers(0, len(q), size=(10000, len(q)))].mean(axis=1)
    lo, hi = np.percentile(boots, [2.5, 97.5])
    print(f"  {b_name} preference score: {q.mean():.3f}  [95% CI {lo:.3f}, {hi:.3f}]  "
          f"(0.5 = no preference; questions B>0.5 / =0.5 / <0.5: "
          f"{(q > 0.5).sum()}/{(q == 0.5).sum()}/{(q < 0.5).sum()})")

    # Reliability: position bias, order consistency, repeat agreement.
    shown_first_won = [r["winner"] == r["shown_first"] for r in rows if r["rating"] in ("A", "B")]
    print(f"  position bias: the answer shown first wins {100 * np.mean(shown_first_won):.0f}% "
          f"of decisive judgments (50% = none)")
    cell = collections.defaultdict(dict)
    for r in rows:
        cell[(r["record_idx"], r["sample_idx"], r["repeat"])][r["order"]] = r["winner"]
    both = [v for v in cell.values() if len(v) == 2]
    if both:
        print(f"  order consistency: same verdict in both orders for {100 * np.mean([v['AB'] == v['BA'] for v in both]):.0f}% "
              f"of {len(both)} comparisons")
    rep = collections.defaultdict(dict)
    for r in rows:
        rep[(r["record_idx"], r["sample_idx"], r["order"])][r["repeat"]] = r["winner"]
    multi = [v for v in rep.values() if len(v) > 1]
    if multi:
        print(f"  repeat agreement: identical prompt, same verdict {100 * np.mean([len(set(v.values())) == 1 for v in multi]):.0f}% "
              f"of {len(multi)} repeated judgments")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--pairs", nargs="+", required=True, help="A:B model names (= eval/generations/<name>.jsonl)")
    ap.add_argument("--gen-dir", default=os.path.join(HERE, "generations"))
    ap.add_argument("--out-dir", default=os.path.join(HERE, "pairwise"))
    ap.add_argument("--judge", default="gpt-5.4")
    ap.add_argument("--repeats", type=int, default=1, help="identical re-judgments, to measure judge reliability")
    ap.add_argument("--workers", type=int, default=20)
    ap.add_argument("--cost-limit", type=float, default=40.0, help="$ cap across all pairs this run")
    ap.add_argument("--report-only", action="store_true")
    args = ap.parse_args()

    os.makedirs(args.out_dir, exist_ok=True)
    pairs = [p.split(":", 1) for p in args.pairs]
    if not args.report_only:
        budget = {"spent": 0.0, "stop": threading.Event()}
        for a, b in pairs:
            run_pair(a, b, args, budget)
        print(f"\njudge spend this run: ${budget['spent']:.2f}")
    for a, b in pairs:
        report(a, b, args)


if __name__ == "__main__":
    main()
